from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import streamlit as st

MODEL_PATH = Path(__file__).parent / "solar_model.pkl"
JOULES_PER_KWH = 3_600_000  # 1 kWh = 3.6 million Joules

# Order must match the order used when the model was trained.
FEATURES = [
    "Distance to solar noon (radians)",
    "Temperature (°C)",
    "Wind direction (degrees)",
    "Wind speed (m/s)",
    "Sky cover (0-4)",
    "Visibility (km)",
    "Humidity (%)",
    "Average wind speed (m/s)",
    "Average pressure (inHg)",
]

PRESETS = {
    "Clear sunny day": dict(noon=0.1, temp=30.0, wdir=180, wspd=3.0, sky=0, vis=10.0, hum=40, avg_wspd=3.0, pres=29.92),
    "Partly cloudy day": dict(noon=0.4, temp=25.0, wdir=180, wspd=4.0, sky=2, vis=10.0, hum=60, avg_wspd=4.0, pres=29.90),
    "Overcast day": dict(noon=0.5, temp=20.0, wdir=200, wspd=5.0, sky=4, vis=6.0, hum=85, avg_wspd=5.0, pres=29.80),
    "Custom": None,
}


@st.cache_resource
def load_model():
    """Load the model once and reuse it on every rerun."""
    return joblib.load(MODEL_PATH)


def predict(model, rows: np.ndarray) -> np.ndarray:
    """Predict and clip negatives (power generated cannot be below zero)."""
    return np.clip(model.predict(rows), 0, None)


st.set_page_config(page_title="Solar Power Prediction", page_icon="☀️", layout="wide")
st.title("☀️ Solar Power Generation Prediction")
st.caption(
    "Predicts the power generated by a solar plant over a 3-hour period "
    "from weather and sun-position inputs, using a Random Forest model."
)

if not MODEL_PATH.exists():
    st.error(f"Model file not found: {MODEL_PATH.name}. Place it in the same folder as App.py.")
    st.stop()

model = load_model()

# ---------------------------------------------------------------- sidebar
with st.sidebar:
    st.header("Quick start")
    preset_name = st.selectbox("Choose a scenario", list(PRESETS))
    st.caption("Pick a ready-made scenario, or choose Custom and set every value yourself.")
    st.divider()
    st.markdown(
        "**About the model**\n\n"
        "Random Forest Regressor trained on weather and sun-position data. "
        "Predictions are most reliable when inputs are close to the range of the training data."
    )

p = PRESETS[preset_name] or PRESETS["Partly cloudy day"]

# ----------------------------------------------------------------- inputs
st.subheader("Enter environmental values")
col1, col2, col3 = st.columns(3)

with col1:
    noon = st.number_input("Distance to solar noon (radians)", 0.0, 3.2, float(p["noon"]), 0.01,
                           help="0 means the sun is at its highest point. Larger values mean earlier morning or later evening.")
    temp = st.number_input("Temperature (°C)", -20.0, 60.0, float(p["temp"]), 0.1)
    sky = st.selectbox("Sky cover (0 = clear, 4 = fully covered)", [0, 1, 2, 3, 4], index=int(p["sky"]))

with col2:
    wdir = st.number_input("Wind direction (degrees)", 0, 360, int(p["wdir"]), 1)
    wspd = st.number_input("Wind speed (m/s)", 0.0, 50.0, float(p["wspd"]), 0.1)
    avg_wspd = st.number_input("Average wind speed (m/s)", 0.0, 50.0, float(p["avg_wspd"]), 0.1)

with col3:
    vis = st.number_input("Visibility (km)", 0.0, 50.0, float(p["vis"]), 0.1)
    hum = st.number_input("Humidity (%)", 0, 100, int(p["hum"]), 1)
    pres = st.number_input("Average pressure (inHg)", 25.0, 32.0, float(p["pres"]), 0.01)

values = [noon, temp, wdir, wspd, sky, vis, hum, avg_wspd, pres]
row = np.array(values, dtype=float).reshape(1, -1)

# ------------------------------------------------------------- prediction
if st.button("Predict power generated", type="primary"):
    joules = float(predict(model, row)[0])
    kwh = joules / JOULES_PER_KWH

    m1, m2 = st.columns(2)
    m1.metric("Predicted power (3-hour period)", f"{joules:,.0f} J")
    m2.metric("Same value in kWh", f"{kwh:.3f} kWh")

    if joules == 0:
        st.info("The model predicts almost no generation for these conditions (for example, very late or early in the day).")

    left, right = st.columns(2)

    with left:
        st.markdown("#### How the sun's position changes the result")
        st.caption("Only distance to solar noon changes here. All your other inputs stay fixed.")
        sweep_x = np.linspace(0, 1.5, 40)
        sweep_rows = np.tile(row, (len(sweep_x), 1))
        sweep_rows[:, 0] = sweep_x
        sweep_df = pd.DataFrame(
            {"Distance to solar noon (radians)": sweep_x, "Predicted power (J)": predict(model, sweep_rows)}
        ).set_index("Distance to solar noon (radians)")
        st.line_chart(sweep_df)

    with right:
        st.markdown("#### How cloud cover changes the result")
        st.caption("Only sky cover changes here. All your other inputs stay fixed.")
        sky_rows = np.tile(row, (5, 1))
        sky_rows[:, 4] = [0, 1, 2, 3, 4]
        sky_df = pd.DataFrame(
            {"Sky cover": ["0 Clear", "1", "2", "3", "4 Covered"], "Predicted power (J)": predict(model, sky_rows)}
        ).set_index("Sky cover")
        st.bar_chart(sky_df)

    # Model feature importance (works for Random Forest and other tree models)
    if hasattr(model, "feature_importances_"):
        st.markdown("#### Which inputs matter most to the model")
        imp = pd.Series(model.feature_importances_, index=FEATURES).sort_values()
        st.bar_chart(imp, horizontal=True)

    with st.expander("See the values used for this prediction"):
        st.table(pd.DataFrame({"Input": FEATURES, "Value": values}))

    # Download the result
    result = pd.DataFrame([values + [joules, kwh]], columns=FEATURES + ["Predicted power (J)", "Predicted power (kWh)"])
    st.download_button("Download this result (CSV)", result.to_csv(index=False), "solar_prediction.csv", "text/csv")

# ------------------------------------------------------------- batch mode
st.divider()
st.subheader("Predict many rows at once (CSV upload)")
st.caption("Upload a CSV with these 9 columns, in this exact order. Column names can be anything.")
st.code(", ".join(FEATURES), language="text")

uploaded = st.file_uploader("Choose a CSV file", type="csv")
if uploaded is not None:
    try:
        data = pd.read_csv(uploaded)
        if data.shape[1] != len(FEATURES):
            st.error(f"Expected {len(FEATURES)} columns but found {data.shape[1]}.")
        elif data.isnull().any().any():
            st.error("The file has empty cells. Please fill or remove them and try again.")
        else:
            data = data.apply(pd.to_numeric, errors="raise")
            data["Predicted power (J)"] = predict(model, data.iloc[:, : len(FEATURES)].to_numpy())
            data["Predicted power (kWh)"] = data["Predicted power (J)"] / JOULES_PER_KWH
            st.success(f"Predicted {len(data)} rows.")
            st.dataframe(data, use_container_width=True)
            st.download_button("Download predictions (CSV)", data.to_csv(index=False), "solar_predictions.csv", "text/csv")
    except Exception as exc:  # show a friendly message instead of a crash
        st.error(f"Could not read the file: {exc}")
